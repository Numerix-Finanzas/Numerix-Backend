-- =====================================================================
-- Numerix - Script de base de datos para PostgreSQL
-- 10 tablas: rol, usuario, negocio, cliente, condicion_credito,
--            producto, compra, obligacion, cuota, pago
--
-- Equivale a lo que crea el backend (entidades JPA). Si el backend usa
-- spring.jpa.hibernate.ddl-auto=create-drop, las tablas las crea Hibernate
-- y este script sirve para el informe o para crear la base a mano.
--
-- Uso:  CREATE DATABASE db_numerix;   -- conectarse a db_numerix y ejecutar
-- =====================================================================

DROP TABLE IF EXISTS pago, cuota, obligacion, compra, producto, condicion_credito,
    usuario, cliente, negocio, rol CASCADE;

-- ---------------------------------------------------------------------
-- Seguridad
-- ---------------------------------------------------------------------
CREATE TABLE rol (
    id_rol  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre  VARCHAR(20) NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (id_rol),
    CONSTRAINT uk_rol_nombre UNIQUE (nombre),
    CONSTRAINT ck_rol_nombre CHECK (nombre IN ('AdminSistema', 'AdminNegocio', 'Cliente'))
);

-- ---------------------------------------------------------------------
-- Negocios, clientes y productos
-- ---------------------------------------------------------------------
CREATE TABLE negocio (
    id_negocio      VARCHAR(20)  NOT NULL,
    nombre_negocio  VARCHAR(100) NOT NULL,
    ruc_negocio     VARCHAR(11)  NOT NULL,
    tipo_negocio    VARCHAR(60),
    estado_negocio  VARCHAR(10)  NOT NULL DEFAULT 'Activo',
    fecha_registro  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_negocio PRIMARY KEY (id_negocio),
    CONSTRAINT uk_negocio_ruc UNIQUE (ruc_negocio),
    CONSTRAINT ck_negocio_ruc CHECK (ruc_negocio ~ '^[0-9]{11}$'),
    CONSTRAINT ck_negocio_estado CHECK (estado_negocio IN ('Activo', 'Inactivo'))
);

CREATE TABLE cliente (
    id_cliente                VARCHAR(20)  NOT NULL,
    id_negocio                VARCHAR(20)  NOT NULL,
    nombre_cliente            VARCHAR(100) NOT NULL,
    tipo_documento_cliente    VARCHAR(10)  NOT NULL DEFAULT 'DNI',
    numero_documento_cliente  VARCHAR(12)  NOT NULL,
    estado_cliente            VARCHAR(8)   NOT NULL DEFAULT 'Activo',
    fecha_registro            TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT uk_cliente_documento UNIQUE (numero_documento_cliente),
    CONSTRAINT fk_cliente_negocio FOREIGN KEY (id_negocio) REFERENCES negocio (id_negocio),
    CONSTRAINT ck_cliente_tipo_documento CHECK (tipo_documento_cliente IN ('DNI', 'CE', 'RUC')),
    CONSTRAINT ck_cliente_estado CHECK (estado_cliente IN ('Activo', 'Inactivo'))
);

-- Condiciones de crédito que el negocio otorga al cliente (1 a 1 con cliente)
CREATE TABLE condicion_credito (
    id_condicion_credito       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente                 VARCHAR(20)   NOT NULL,
    moneda                     VARCHAR(3)    NOT NULL DEFAULT 'PEN',
    limite_credito             NUMERIC(18,2) NOT NULL,
    tipo_tasa                  VARCHAR(10)   NOT NULL DEFAULT 'Efectiva',
    porcentaje_tasa            NUMERIC(18,7) NOT NULL,
    tipo_tasa_moratoria        VARCHAR(10)   NOT NULL DEFAULT 'Efectiva',
    porcentaje_tasa_moratoria  NUMERIC(18,7) NOT NULL,
    periodo_tasa               VARCHAR(15)   NOT NULL DEFAULT 'Mensual',
    periodo_capitalizacion     INTEGER       NOT NULL DEFAULT 30,
    dia_corte                  INTEGER       NOT NULL DEFAULT 25,
    dia_pago_pactado           INTEGER       NOT NULL DEFAULT 30,
    maximo_meses_credito       INTEGER       NOT NULL DEFAULT 1,
    CONSTRAINT pk_condicion_credito PRIMARY KEY (id_condicion_credito),
    CONSTRAINT uk_condicion_credito_cliente UNIQUE (id_cliente),
    CONSTRAINT fk_condicion_credito_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente),
    CONSTRAINT ck_condicion_moneda CHECK (moneda IN ('PEN', 'USD')),
    CONSTRAINT ck_condicion_limite CHECK (limite_credito > 0),
    CONSTRAINT ck_condicion_tipo_tasa CHECK (tipo_tasa IN ('Nominal', 'Efectiva')),
    CONSTRAINT ck_condicion_tipo_tasa_moratoria CHECK (tipo_tasa_moratoria IN ('Nominal', 'Efectiva')),
    CONSTRAINT ck_condicion_tasas CHECK (porcentaje_tasa > 0 AND porcentaje_tasa_moratoria > 0),
    CONSTRAINT ck_condicion_periodo_tasa CHECK (periodo_tasa IN ('Diario', 'Mensual', 'Trimestral', 'Semestral', 'Anual')),
    CONSTRAINT ck_condicion_capitalizacion CHECK (periodo_capitalizacion > 0),
    CONSTRAINT ck_condicion_dia_corte CHECK (dia_corte BETWEEN 1 AND 30),
    CONSTRAINT ck_condicion_dia_pago CHECK (dia_pago_pactado BETWEEN 1 AND 30),
    CONSTRAINT ck_condicion_maximo_meses CHECK (maximo_meses_credito > 0)
);

CREATE TABLE producto (
    id_producto               VARCHAR(20)   NOT NULL,
    id_negocio                VARCHAR(20)   NOT NULL,
    descripcion_producto      VARCHAR(150)  NOT NULL,
    marca_producto            VARCHAR(50),
    proveedor_producto        VARCHAR(100),
    unidad_medida             VARCHAR(20)   NOT NULL DEFAULT 'Unidad',
    imagen_producto           VARCHAR(255),
    precio_contado            NUMERIC(18,2) NOT NULL,
    precio_credito            NUMERIC(18,2) NOT NULL,
    modalidad_venta_producto  VARCHAR(10)   NOT NULL,
    estado_producto           VARCHAR(10)   NOT NULL DEFAULT 'Activo',
    fecha_registro            TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_producto PRIMARY KEY (id_producto),
    CONSTRAINT fk_producto_negocio FOREIGN KEY (id_negocio) REFERENCES negocio (id_negocio),
    CONSTRAINT ck_producto_precios CHECK (precio_contado > 0 AND precio_credito >= precio_contado),
    CONSTRAINT ck_producto_modalidad CHECK (modalidad_venta_producto IN ('Contado', 'Crédito', 'Ambas')),
    CONSTRAINT ck_producto_estado CHECK (estado_producto IN ('Activo', 'Inactivo'))
);

-- Cuenta de acceso: AdminSistema (sin negocio), AdminNegocio (con negocio) o Cliente (con cliente)
CREATE TABLE usuario (
    id_usuario          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario             VARCHAR(20)  NOT NULL,
    contrasena          VARCHAR(64)  NOT NULL,   -- hash BCrypt
    id_rol              BIGINT       NOT NULL,
    nombre_completo     VARCHAR(100),
    correo_electronico  VARCHAR(100),
    id_negocio          VARCHAR(20),
    id_cliente          VARCHAR(20),
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro      TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uk_usuario_usuario UNIQUE (usuario),
    CONSTRAINT uk_usuario_cliente UNIQUE (id_cliente),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol),
    CONSTRAINT fk_usuario_negocio FOREIGN KEY (id_negocio) REFERENCES negocio (id_negocio),
    CONSTRAINT fk_usuario_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
);

-- ---------------------------------------------------------------------
-- Operaciones de crédito
-- ---------------------------------------------------------------------
CREATE TABLE compra (
    id_compra                VARCHAR(20)   NOT NULL,
    id_cliente               VARCHAR(20)   NOT NULL,
    id_producto              VARCHAR(20)   NOT NULL,
    fecha_compra             DATE          NOT NULL DEFAULT CURRENT_DATE,
    cantidad_producto        INTEGER       NOT NULL DEFAULT 1,
    tipo_pago                VARCHAR(15)   NOT NULL DEFAULT 'Un solo pago',
    numero_cuotas            INTEGER       NOT NULL DEFAULT 1,
    precio_credito_aplicado  NUMERIC(18,2) NOT NULL,
    monto_compra             NUMERIC(18,2) NOT NULL,   -- cantidad_producto x precio_credito
    fecha_registro           TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_compra PRIMARY KEY (id_compra),
    CONSTRAINT fk_compra_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente),
    CONSTRAINT fk_compra_producto FOREIGN KEY (id_producto) REFERENCES producto (id_producto),
    CONSTRAINT ck_compra_cantidad CHECK (cantidad_producto > 0),
    CONSTRAINT ck_compra_tipo_pago CHECK (tipo_pago IN ('Un solo pago', 'Cuotas')),
    CONSTRAINT ck_compra_cuotas CHECK (numero_cuotas > 0),
    CONSTRAINT ck_compra_monto CHECK (monto_compra > 0)
);

-- Obligación de pago de una compra; guarda una copia de las tasas del cliente al comprar
CREATE TABLE obligacion (
    id_obligacion              VARCHAR(20)   NOT NULL,
    id_compra                  VARCHAR(20)   NOT NULL,
    moneda                     VARCHAR(3)    NOT NULL,
    tipo_tasa                  VARCHAR(10)   NOT NULL,
    porcentaje_tasa            NUMERIC(18,7) NOT NULL,
    periodo_tasa               VARCHAR(15)   NOT NULL,
    periodo_capitalizacion     INTEGER       NOT NULL,
    tipo_tasa_moratoria        VARCHAR(10)   NOT NULL,
    porcentaje_tasa_moratoria  NUMERIC(18,7) NOT NULL,
    capital_inicial            NUMERIC(18,2) NOT NULL,
    capital_actualizado        NUMERIC(18,2) NOT NULL,   -- con los días de gracia capitalizados
    dias_gracia                INTEGER       NOT NULL DEFAULT 0,
    fecha_registro             TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_obligacion PRIMARY KEY (id_obligacion),
    CONSTRAINT uk_obligacion_compra UNIQUE (id_compra),
    CONSTRAINT fk_obligacion_compra FOREIGN KEY (id_compra) REFERENCES compra (id_compra),
    CONSTRAINT ck_obligacion_capital CHECK (capital_actualizado >= capital_inicial),
    CONSTRAINT ck_obligacion_dias_gracia CHECK (dias_gracia >= 0)
);

-- Cuotas del cronograma (una sola cuota si la compra es a un solo pago)
CREATE TABLE cuota (
    id_cuota               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_obligacion          VARCHAR(20)   NOT NULL,
    numero_cuota           INTEGER       NOT NULL,
    fecha_vencimiento      DATE          NOT NULL,
    saldo_inicial          NUMERIC(18,2) NOT NULL,
    interes_compensatorio  NUMERIC(18,2) NOT NULL,
    amortizacion           NUMERIC(18,2) NOT NULL,
    monto_cuota            NUMERIC(18,2) NOT NULL,
    saldo_final            NUMERIC(18,2) NOT NULL,
    pagada                 BOOLEAN       NOT NULL DEFAULT FALSE,
    fecha_pago             DATE,
    CONSTRAINT pk_cuota PRIMARY KEY (id_cuota),
    CONSTRAINT uk_cuota_obligacion_numero UNIQUE (id_obligacion, numero_cuota),
    CONSTRAINT fk_cuota_obligacion FOREIGN KEY (id_obligacion) REFERENCES obligacion (id_obligacion),
    CONSTRAINT ck_cuota_numero CHECK (numero_cuota > 0),
    CONSTRAINT ck_cuota_montos CHECK (interes_compensatorio >= 0 AND amortizacion >= 0 AND saldo_final >= 0)
);

-- Pago de una cuota, imputado en el orden mora -> interés compensatorio -> capital
CREATE TABLE pago (
    id_pago                 VARCHAR(20)   NOT NULL,
    id_obligacion           VARCHAR(20)   NOT NULL,
    id_cuota                BIGINT        NOT NULL,
    fecha_pago_real         DATE          NOT NULL,
    monto_pagado            NUMERIC(18,2) NOT NULL,
    monto_imputado_mora     NUMERIC(18,2) NOT NULL DEFAULT 0,
    monto_imputado_interes  NUMERIC(18,2) NOT NULL DEFAULT 0,
    monto_imputado_capital  NUMERIC(18,2) NOT NULL DEFAULT 0,
    dias_mora               INTEGER       NOT NULL DEFAULT 0,
    dias_anticipacion       INTEGER       NOT NULL DEFAULT 0,
    fecha_registro          TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_pago PRIMARY KEY (id_pago),
    CONSTRAINT uk_pago_cuota UNIQUE (id_cuota),
    CONSTRAINT fk_pago_obligacion FOREIGN KEY (id_obligacion) REFERENCES obligacion (id_obligacion),
    CONSTRAINT fk_pago_cuota FOREIGN KEY (id_cuota) REFERENCES cuota (id_cuota),
    CONSTRAINT ck_pago_monto CHECK (monto_pagado > 0),
    CONSTRAINT ck_pago_imputacion CHECK (monto_imputado_mora + monto_imputado_interes + monto_imputado_capital = monto_pagado),
    CONSTRAINT ck_pago_dias CHECK (dias_mora >= 0 AND dias_anticipacion >= 0)
);

-- Índices para las búsquedas más frecuentes (por negocio, por cliente y por fechas)
CREATE INDEX ix_cliente_negocio ON cliente (id_negocio);
CREATE INDEX ix_producto_negocio ON producto (id_negocio);
CREATE INDEX ix_compra_cliente_fecha ON compra (id_cliente, fecha_compra);
CREATE INDEX ix_pago_obligacion_fecha ON pago (id_obligacion, fecha_pago_real);

